//! Host-owned Tailscale invitation administration, separate from application pairing.
//!
//! `TAILSCALE_API_KEY` must be a user-owned admin API key. An enrollment auth key
//! cannot administer invitations; OAuth access tokens cannot create invitations.
//! Neither this credential nor a network invitation authorizes Durop commands.

use reqwest::{
    Client, Method, Url,
    header::{AUTHORIZATION, HeaderValue},
};
use serde::Deserialize;
use std::{future::Future, pin::Pin, time::Duration};

mod secrets;

pub use secrets::{PlatformSecretStore, SecretStore};

// Fixed official origin; callers cannot redirect credentials to arbitrary hosts.
const API_ORIGIN: &str = "https://api.tailscale.com/api/v2/";
// Bound response allocation even when Content-Length is absent or misleading.
const MAX_RESPONSE: usize = 256 * 1024;

/// Sanitized administration failures. Display/Debug never include tokens, URLs,
/// response bodies, local storage paths or upstream error text.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum InvitationError {
    /// Input is malformed or an enrollment/auth key was supplied instead of an API key.
    InvalidInput,
    /// The user-owned API key is invalid, expired, or lacks required permissions.
    Unauthorized,
    /// Tailscale rejected the target or invitation identifier.
    NotFound,
    /// The upstream request exceeded its bounded deadline.
    Timeout,
    /// The upstream service rate limited administration requests.
    RateLimited,
    /// TLS, connection, response validation or upstream service failure.
    Unavailable,
    /// Secure storage failed or its permissions did not satisfy the contract.
    Storage,
}

impl std::fmt::Display for InvitationError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::InvalidInput => "enter a user-owned Tailscale API key and valid invitation target",
            Self::Unauthorized => "Tailscale denied access; use an unexpired user-owned API key with invitation permissions",
            Self::NotFound => "Tailscale invitation or device was not found",
            Self::Timeout => "Tailscale invitation request timed out",
            Self::RateLimited => "Tailscale invitation requests are temporarily rate limited",
            Self::Unavailable => "Tailscale invitation service is unavailable",
            Self::Storage => "secure credential storage is unavailable",
        })
    }
}

impl std::error::Error for InvitationError {}

/// User-owned Tailscale admin API key; never provide this to a controller.
/// Debug is redacted. Ownership and current permissions are verified by Tailscale.
pub struct AdminApiKey(String);

impl std::fmt::Debug for AdminApiKey {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("AdminApiKey([REDACTED])")
    }
}

impl AdminApiKey {
    /// Validate the API-key shape and reject enrollment auth keys/OAuth client secrets.
    /// Tokens generated by OAuth can resemble API keys; the server rejects those
    /// for invitation creation, which requires an inviting user.
    pub fn from_secret(secret: String) -> Result<Self, InvitationError> {
        if !secret.starts_with("tskey-api-")
            || !(16..=1024).contains(&secret.len())
            || !secret
                .bytes()
                .all(|byte| byte.is_ascii_alphanumeric() || byte == b'-')
        {
            return Err(InvitationError::InvalidInput);
        }
        Ok(Self(secret))
    }

    /// Read `TAILSCALE_API_KEY` without logging it or modifying process environment.
    /// Missing configuration returns None; malformed/non-Unicode values fail closed.
    pub fn from_environment() -> Result<Option<Self>, InvitationError> {
        match std::env::var("TAILSCALE_API_KEY") {
            Ok(secret) => Self::from_secret(secret).map(Some),
            Err(std::env::VarError::NotPresent) => Ok(None),
            Err(_) => Err(InvitationError::InvalidInput),
        }
    }
}

/// Explicit network admission scope. Device sharing is preferred for host-only
/// guest access; tailnet membership is available only as an intentional choice.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum InvitationTarget {
    /// Share one local host device, without granting exit-node permission.
    Device(String),
    /// Invite a member to the named tailnet; never grants an administration role.
    Tailnet(String),
}

impl InvitationTarget {
    // Encode each ID as one URL segment; a caller can never alter the fixed origin.
    fn endpoint(&self, invitation_id: Option<&str>) -> Result<Url, InvitationError> {
        let (id, prefix, suffix) = match self {
            Self::Device(id) => (id, "device", "device-invites"),
            Self::Tailnet(id) => (id, "tailnet", "user-invites"),
        };
        if id.is_empty() || id.len() > 256 || id.chars().any(char::is_control) {
            return Err(InvitationError::InvalidInput);
        }
        let mut url = Url::parse(API_ORIGIN).map_err(|_| InvitationError::Unavailable)?;
        {
            let mut segments = url
                .path_segments_mut()
                .map_err(|_| InvitationError::Unavailable)?;
            segments.pop_if_empty();
            if let Some(invitation_id) = invitation_id {
                if invitation_id.is_empty()
                    || invitation_id.len() > 128
                    || !invitation_id
                        .bytes()
                        .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_'))
                {
                    return Err(InvitationError::InvalidInput);
                }
                segments.push(suffix).push(invitation_id);
            } else {
                segments.push(prefix).push(id).push(suffix);
            }
        }
        Ok(url)
    }

    // Fixed least-privilege request body. No implicit email is sent.
    fn create_body(&self) -> serde_json::Value {
        match self {
            Self::Device(_) => serde_json::json!([{"multiUse":false,"allowExitNode":false}]),
            Self::Tailnet(_) => serde_json::json!([{"role":"member"}]),
        }
    }
}

/// Invitation projection. Its URL is sensitive and only for explicit sharing UI.
#[derive(Clone, Deserialize, Eq, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Invitation {
    /// Opaque upstream ID, used for explicit revocation.
    pub id: String,
    /// Official HTTPS acceptance URL; never includes the admin credential.
    pub invite_url: String,
    /// Whether a device invitation was already accepted; absent user flags are false.
    #[serde(default)]
    pub accepted: bool,
}

impl std::fmt::Debug for Invitation {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Invitation")
            .field("id", &self.id)
            .field("invite_url", &"[REDACTED]")
            .field("accepted", &self.accepted)
            .finish()
    }
}

/// Sendable, cancellable administration operation, usable behind a trait object.
pub type InvitationFuture<'a, T> =
    Pin<Box<dyn Future<Output = Result<T, InvitationError>> + Send + 'a>>;

/// Interchangeable network-admission provider with bounded asynchronous operations.
/// Dropping a future cancels the local request; after transmission the server may
/// still have applied a mutation, so callers must list to reconcile uncertainty.
pub trait InvitationProvider: Send + Sync {
    /// Create one least-privilege invitation without emailing it automatically.
    fn create(&self, target: InvitationTarget) -> InvitationFuture<'_, Invitation>;

    /// List this target's invitations; does not list unrelated tailnet devices.
    fn list(&self, target: InvitationTarget) -> InvitationFuture<'_, Vec<Invitation>>;

    /// Revoke an invitation by ID. Revoking Durop pairing is a separate operation;
    /// an accepted device share may need explicit removal in Tailscale administration.
    fn revoke(&self, target: InvitationTarget, invitation_id: String) -> InvitationFuture<'_, ()>;
}

/// Fixed-origin HTTPS implementation with ten-second deadlines, no redirects,
/// no implicit proxies, at most two in-flight requests, bounded response bodies
/// and sanitized upstream failures.
pub struct TailscaleInvitations {
    // Reused bounded HTTPS client; it cannot follow redirects or caller-selected hosts.
    client: Client,
    // Sensitive header is redacted by the HTTP implementation.
    authorization: HeaderValue,
    // Reject excess simultaneous operations instead of growing an unbounded request queue.
    slots: tokio::sync::Semaphore,
}

impl TailscaleInvitations {
    /// Own the host credential. It appears only in a sensitive HTTP header, never
    /// in subprocess arguments, URLs, response projections, or debug formatting.
    pub fn new(key: AdminApiKey) -> Result<Self, InvitationError> {
        let mut authorization = HeaderValue::from_str(&format!("Bearer {}", key.0))
            .map_err(|_| InvitationError::InvalidInput)?;
        authorization.set_sensitive(true);
        let client = Client::builder()
            .https_only(true)
            .no_proxy()
            .redirect(reqwest::redirect::Policy::none())
            .connect_timeout(Duration::from_secs(3))
            .timeout(Duration::from_secs(10))
            .build()
            .map_err(|_| InvitationError::Unavailable)?;
        Ok(Self {
            client,
            authorization,
            slots: tokio::sync::Semaphore::new(2),
        })
    }

    // Preserve only fixed error categories, never upstream bodies/headers/URLs.
    async fn request(
        &self,
        method: Method,
        target: &InvitationTarget,
        id: Option<&str>,
    ) -> Result<Vec<u8>, InvitationError> {
        let _slot = self
            .slots
            .try_acquire()
            .map_err(|_| InvitationError::RateLimited)?;
        let mut request = self
            .client
            .request(method.clone(), target.endpoint(id)?)
            .header(AUTHORIZATION, self.authorization.clone());
        if method == Method::POST {
            request = request.json(&target.create_body());
        }
        let mut response = request.send().await.map_err(Self::network_error)?;
        match response.status().as_u16() {
            200..=299 => {}
            401 | 403 => return Err(InvitationError::Unauthorized),
            404 => return Err(InvitationError::NotFound),
            429 => return Err(InvitationError::RateLimited),
            _ => return Err(InvitationError::Unavailable),
        }
        if response
            .content_length()
            .is_some_and(|length| length > MAX_RESPONSE as u64)
        {
            return Err(InvitationError::Unavailable);
        }
        let mut body = Vec::new();
        while let Some(chunk) = response.chunk().await.map_err(Self::network_error)? {
            if body.len() + chunk.len() > MAX_RESPONSE {
                return Err(InvitationError::Unavailable);
            }
            body.extend_from_slice(&chunk);
        }
        Ok(body)
    }

    // reqwest errors may contain request URLs; never wrap their display/debug values.
    fn network_error(error: reqwest::Error) -> InvitationError {
        if error.is_timeout() {
            InvitationError::Timeout
        } else {
            InvitationError::Unavailable
        }
    }

    // Validate all returned links before exposing them to a browser/copy affordance.
    fn parse(body: &[u8]) -> Result<Vec<Invitation>, InvitationError> {
        let invitations: Vec<Invitation> =
            serde_json::from_slice(body).map_err(|_| InvitationError::Unavailable)?;
        if invitations.len() > 256
            || invitations.iter().any(|invitation| {
                invitation.id.is_empty()
                    || invitation.id.len() > 128
                    || invitation.invite_url.len() > 2048
                    || !Url::parse(&invitation.invite_url).is_ok_and(|url| {
                        url.scheme() == "https"
                            && url.host_str() == Some("login.tailscale.com")
                            && url.port().is_none()
                            && url.username().is_empty()
                            && url.password().is_none()
                            && (url.path().starts_with("/admin/invite/")
                                || url.path().starts_with("/uinv/"))
                    })
            })
        {
            return Err(InvitationError::Unavailable);
        }
        Ok(invitations)
    }
}

impl InvitationProvider for TailscaleInvitations {
    fn create(&self, target: InvitationTarget) -> InvitationFuture<'_, Invitation> {
        Box::pin(async move {
            let mut invitations = Self::parse(&self.request(Method::POST, &target, None).await?)?;
            if invitations.len() != 1 {
                return Err(InvitationError::Unavailable);
            }
            Ok(invitations.remove(0))
        })
    }

    fn list(&self, target: InvitationTarget) -> InvitationFuture<'_, Vec<Invitation>> {
        Box::pin(async move { Self::parse(&self.request(Method::GET, &target, None).await?) })
    }

    fn revoke(&self, target: InvitationTarget, invitation_id: String) -> InvitationFuture<'_, ()> {
        Box::pin(async move {
            self.request(Method::DELETE, &target, Some(&invitation_id))
                .await
                .map(|_| ())
        })
    }
}

